"""Render the generated parameter document.

The document ``docs/source/mujoco_parameters.md`` is written only by
``python -m ariel.simulators.mujoco --write-docs``, never by hand. A test
renders it again and compares, so a stale file fails the CI.
"""

# Standard library
from pathlib import Path

# Third-party libraries
import mujoco

# Local libraries
from ariel.simulators.mujoco.bands import BandResult, evaluate_bands
from ariel.simulators.mujoco.bands import summary as band_summary
from ariel.simulators.mujoco.mjcf import differences
from ariel.simulators.mujoco.mjcf import summary as difference_summary
from ariel.simulators.mujoco.seeds import Seeds
from ariel.simulators.mujoco.settings import Value, engine_defaults
from ariel.simulators.mujoco.table import Row, derivation_table

REPO_ROOT = Path(__file__).resolve().parents[4]
DOCS_PATH = REPO_ROOT / "docs" / "source" / "mujoco_parameters.md"


def _show(value: Value) -> str:
    """Format a value for a table cell.

    Parameters
    ----------
    value : Value
        A setting value.

    Returns
    -------
    str
        Numbers in general format, tuples separated by spaces.
    """
    if isinstance(value, tuple):
        return " ".join(f"{item:g}" for item in value)
    if isinstance(value, bool):
        return str(value)
    return f"{value:g}" if isinstance(value, int | float) else str(value)


def _row_lines(rows: list[Row]) -> list[str]:
    """Format derivation rows as table lines.

    Parameters
    ----------
    rows : list[Row]
        The derivation table.

    Returns
    -------
    list[str]
        One markdown table line per row.
    """
    return [
        f"| `{row.name}` | {row.value:g} | {row.unit} | {row.kind} "
        f"| {row.source} |"
        for row in rows
    ]


def _band_lines(results: list[BandResult]) -> list[str]:
    """Format band results as table lines.

    Parameters
    ----------
    results : list[BandResult]
        The checked bands.

    Returns
    -------
    list[str]
        One markdown table line per band.
    """
    return [
        f"| `{result.name}` | {result.value:g} | {result.low:g} to "
        f"{result.high:g} | {result.unit} | {'yes' if result.inside else 'NO'} "
        f"| {result.basis} |"
        for result in results
    ]


def render_markdown(seeds: Seeds) -> str:
    """Render the document for a set of seeds.

    Parameters
    ----------
    seeds : Seeds
        The physical scales.

    Returns
    -------
    str
        The markdown text.
    """
    defaults = engine_defaults()
    results = evaluate_bands(seeds)
    lines = [
        "# MuJoCo parameters",
        "",
        (
            "<!-- Generated by `python -m ariel.simulators.mujoco "
            "--write-docs`. Do not edit by hand. -->"
        ),
        "",
        (
            f"Generated for MuJoCo {mujoco.__version__} from the default "
            "seeds. Every world starts from these settings; any value not "
            "listed here is MuJoCo's own default."
        ),
        "",
        "## Seeds and formulas",
        "",
        "| Name | Value | Unit | Kind | Source |",
        "|---|---|---|---|---|",
        *_row_lines(derivation_table(seeds)),
        "",
        "## Differences from MuJoCo's defaults",
        "",
        f"{difference_summary(seeds)}.",
        "",
        "| Setting | MuJoCo default | Value | Kind | Reason | Source |",
        "|---|---|---|---|---|---|",
        *(
            f"| `{setting.name}` | {_show(defaults[setting.name])} "
            f"| {_show(setting.value)} | {setting.kind} | {setting.reason} "
            f"| {setting.source} |"
            for setting in differences(seeds)
        ),
        "",
        "## Plausible bands",
        "",
        f"{band_summary(results)}.",
        "",
        "| Quantity | Value | Band | Unit | Inside | Basis |",
        "|---|---|---|---|---|---|",
        *_band_lines(results),
        "",
    ]
    return "\n".join(lines)


def write_docs(path: Path | None = None) -> Path:
    """Write the document for the default seeds.

    Parameters
    ----------
    path : Path | None
        Where to write; ``DOCS_PATH`` when None.

    Returns
    -------
    Path
        The file written.
    """
    target = DOCS_PATH if path is None else path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_markdown(Seeds()), encoding="utf-8")
    return target
